def generate_policy():
    """生成售后政策：基础规则 + 类目×平台规则 + 各平台政策文档"""
    rules = []
    docs = {}
    for platform, items in POLICY_TEMPLATES.items():
        lines = [f"# {platform} 售后政策", ""]
        for idx, (title, cat, content) in enumerate(items):
            rule_id = f"{platform}-RULE-{idx + 1:03d}"
            rules.append({
                "rule_id": rule_id,
                "platform": platform,
                "category": cat,
                "title": title,
                "content": content,
            })
            lines.append(f"## {idx + 1}. {title}（{cat}）")
            lines.append("")
            lines.append(content)
            lines.append("")
        # 类目×平台 退换货规则
        lines.append("")
        lines.append("## 类目退换货规则")
        lines.append("")
        for cat_name in [c[0] for c in CATEGORIES]:
            ret_rule, warranty = CATEGORY_RETURN_TYPE.get(cat_name, ("支持7天无理由退货", "支持退换"))
            content = f"{cat_name}类目在{platform}平台：{ret_rule}；保修/三包说明：{warranty}。"
            rule_id = f"{platform}-CAT-{cat_name}"
            rules.append({
                "rule_id": rule_id,
                "platform": platform,
                "category": cat_name,
                "title": f"{cat_name}类目退换货政策",
                "content": content,
            })
            lines.append(f"- **{cat_name}**：{content}")
        docs[platform] = "\n".join(lines)
    return rules, docs


